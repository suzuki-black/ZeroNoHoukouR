; pcm.s — turbo R 内蔵 PCM の非同期再生(1 声)。
;
; ★狙いは「ゲームを止めずに鳴らす」。鳴り終わるまで待つのではなく、**鳴っている間だけ走査線割込みを
;   サンプルの行にも張り、1 サンプルずつ時刻どおりに出す**(hot_pcm.s。raster.c の ras_next が呼ぶ)。
;   ★最初は「ゲームが待っている合間」に出していたが、面中は待ち時間が 6〜20% しか無く崩れた(2026-10-08 に変更)。
;
; ポート
;   A4h 書込: サンプル値(8bit unsigned、中心 0x80)
;   A5h 書込: bit0 BUFF(1=次の刻みで D/A へ) / bit1 MUTE(★0 にすると PSG も FM も消える)
;             bit2 FILT / bit3 SEL(0=D/A)
;   E6h/E7h : システムタイマ(1 カウント 3.911us)。**時刻はここで取る**
;
; ★間隔は「前回の予定 + PCM_PERIOD」で進める(今の時刻からではない)。遅れても次で詰めて取り返すので
;   再生速度が伸びない。A4h の 2bit カウンタを見る方式は、書くとカウンタが 0 に戻るうえ 254us で
;   一周するため、出遅れた分がそのまま間隔に足されて音が伸びる。
; ★1ms 以上遅れたら取り返しを諦めて予定を今に合わせ直す(音は伸びるが、途切れたままにはならない)。
;
; ■ なぜ自己書き換えを使わないか
;   先行実装は送出口の命令を書き換えて「鳴っていないときは JR 1 命令」にしているが、あれは
;   **プログラム全体を RAM へ展開して動かしている**から成立する。本作の常駐は
;   「カート ROM」と「RAM 複製」の 2 つの姿を持ち、どちらが見えているかが場面で変わるので、
;   コードの書き換えは成立しない。状態は必ず _DATA(RAM) に置き、出す側(hot_pcm.s)は素直に call する。
;
; ■ 1 声でよい理由と、その例外
;   面中はスネア、タイトルと結果画面は叫び。声を増やすと足し算と休符の処理が要るので増やさない。
;   ★ただし**同時に鳴る場面が無い、は誤りだった**。叫びは「タイトル曲を鳴らしたまま」出すので、
;     叫んでいる最中にスネアの拍が来る。そのとき pcm_snare が位置と残数を上書きし、
;     **拍 1 回で叫びが死ぬ**(実測: A4 への書込みが 192 = 叫びの出だし 64 + スネアの全長 128)。
;   → 1 声しか無いなら**優先順位を決める**しかない。_pcm_lock を立てている間はスネアが譲る。
;     錠は voice_play / voice_fanfare が掛け、_pcm_stop(鳴り終わり・打ち切り)が外す。

	.module	pcm
	.globl	_pcm_start, _pcm_stop, _pcm_snare, _pcm_active, _pcm_lock, _g_pcm_src, _g_pcm_len, _g_pcm

PCM_DATA   = 0xA4
PCM_CTRL   = 0xA5
PCM_TIMER  = 0xE6		; システムタイマ下位(1 カウント 3.911us)

; ★★ここが標本化の唯一の出どころ。tools/gen_snare.py がこのファイルを読んで
;   同じ値で波形を作る。片方だけ変えると音程が狂うので、**必ずここだけを直すこと**。
;
; ★なぜ 7993Hz をやめたか(実測)。この方式は「ゲームが待っている合間に 1 サンプルずつ出す」。
;   ところがゲームが差し出す送出の機会を openMSX(実機BIOS機)で画面ごとに数えたら、
;
;     タイトル 0 / 面の切替 2334 / 開始カード 5277 / ゲーム中(海) 18264 / ゲーム中(戦艦) 1557  回/秒
;
;   で、**戦艦の区間が 1557 回/秒しか無い**。7993Hz では 5 倍に間延びし、1 発 32ms が 300ms 以上
;   かかって次の拍に食われていた(99 発中 51 発が重なり)。描画が重く待ち時間がほぼゼロの区間がある、
;   というのがこの作りの前提と合っていなかった。
PCM_PERIOD = 64			; 64 x 3.911us = 250.3us = 3996Hz

	.area	_DATA
; ★状態は必ず RAM(_DATA)。crt0 が 0 クリアするので初期値は持てない(持たせない作りにしてある)
pcm_p:		.ds	2	; いま読んでいる位置
pcm_n:		.ds	2	; 残りバイト数
_pcm_due::	.ds	2	; 次に出す予定の時刻(システムタイマ 16bit)。★大域: hot_pcm.s(割込みで出す)も読む
_pcm_active::	.ds	1	; 0 以外 = 再生中。鳴り終わりを待つ側が見る
_pcm_lock::	.ds	1	; 0 以外 = 叫びが鳴っている。スネアは譲る(優先順位。下の _pcm_snare 参照)
_g_pcm_src::	.ds	2	; C が入れる: サンプルの先頭(RAM 番地)
_g_pcm_len::	.ds	2	; 同: 長さ(バイト)
; ★_g_pcm(1=使ってよい)は **gamestate.c** にある。既定を 1 にしたいが、crt0 は _DATA を
;   0 クリアするので、ここ(_DATA)に置くと既定 OFF になってしまう。

	.area	_CODE

; ---------------------------------------------------------------------------
; void pcm_start(void)   g_pcm_src / g_pcm_len に入れてから呼ぶ
;   ★引数を取らないのは、スタック越しの受け渡しが常駐では高くつくため
;   前の音が鳴っていても、そのまま新しい音へ差し替える(スネアの連打はこれで切り替わる)
; ---------------------------------------------------------------------------
; ---------------------------------------------------------------------------
; void pcm_snare(void) — 面中のスネア専用。番地と長さを**ここで持つ**。
;   ★ISR(bgm_drum)から呼ぶので、呼ぶ側を 1 命令にしたい。g_pcm_src/g_pcm_len を
;     毎回積むと常駐が 20B ほど増えるため、固定のものは asm 側に持たせる。
;   ★番地は常駐 RAM の高位フリー帯(pcm.h の PCM_SNARE_ADDR と合わせること)。
; ---------------------------------------------------------------------------
; ★番地は pcm.h の PCM_SNARE_ADDR と合わせること(置き場所の経緯も pcm.h)。枠は 256B。
; ★長さを 80(20ms)まで詰めたことがあるが、**耳には悪化した**ので 128 に戻した。
;   「出せる予算(実測で平均 87.5 サンプル)に合わせれば毎回鳴り切る」という読みだったが、
;   実際に起きたのはこうだった(openMSX、戦艦の区間で 60 秒、発火 101 回):
;
;                満額で鳴った   潰れた回数   潰れたとき出ていた量
;     128 発      59 (58%)      42          約 29 サンプル(7ms) = 短いがスネアらしい音
;      80 発      69 (68%)      31          約 **4.5 サンプル(1ms)** = ただのクリック音
;
;   満額の割合は上がるが、**外したときの残骸がクリック音になる**ので全体では汚く聞こえる。
;   ★「平均」や「成功率」だけ見て、**外したときに何が鳴っているか**を見ていなかった。
PCM_SNARE_ADDR = 0xEB00
PCM_SNARE_LEN  = 128		; 32ms @ 3996Hz (枠 256B のうち 128B を使う)
; ★★この入口は**割込みを触らない**。理由と、使うときの約束:
;   ・いまの呼び出し元は _pcm_snare ← bgm_drum ← ISR だけ。ISR は元から割込みを止めて
;     いるので、ここで di する必要が無く、**ei してはいけない**(割込みの中で割込みを
;     開けると、BIOS の割込み処理の途中で多重割込みが入り音の処理が再入する)。
;   ・**本体ループから呼ぶときは、呼ぶ側が di〜ei で囲むこと。** ISR(_pcm_snare)に
;     割り込まれると状態が半端なまま書き換わる。叫び(タイトル/結果画面)を入れる段で
;     前景用の入口を足す予定。そのとき、ここに di〜ei 版をもう 1 つ生やす。
;   ・一度その前景用入口を先に作ったが、呼ぶ人が居ないのに常駐を 8B 食い、
;     SPINTEST(検証ROM)がその 8B で溢れたので、要るときに作ることにした。
_pcm_snare::
	ld	a, (_pcm_lock)		; ★叫びが鳴っている間は譲る
	or	a, a
	ret	nz
	ld	hl, #PCM_SNARE_LEN
	ld	(_g_pcm_len), hl
	ld	hl, #PCM_SNARE_ADDR
	ld	(_g_pcm_src), hl
	; ↓ そのまま再生開始へ落ちる

_pcm_start::
	ld	a, (_g_pcm)		; 使えない機械(検出で落ちた/設定で OFF)では何もしない
	or	a, a
	ret	z
	ld	hl, (_g_pcm_len)
	ld	a, h
	or	a, l
	ret	z
	ld	(pcm_n), hl
	ld	hl, (_g_pcm_src)
	ld	(pcm_p), hl
	ld	a, #0x03		; BUFF=1, MUTE 解除(bit1=1), D/A
	out	(PCM_CTRL), a
	call	pcm_now			; 最初の 1 つはすぐ出す
	ld	(_pcm_due), hl
	ld	a, #1
	ld	(_pcm_active), a
	jr	pcm_feed

; ---- void pcm_stop(void) ----
; ★鳴っていなければ何もしない。鳴らせない機械(検出で落ちた)で A4h を叩かないため。
; ★叫びの錠もここで外す。何も鳴っていないなら守るものも無い。鳴り終わり(pcm_last)でも、
;   叫びを打ち切ったとき(voice_play の上限・voice_fanfare)でも、ここを通れば錠が外れる。
_pcm_stop::
	ld	a, (_pcm_active)
	or	a, a
	ret	z
	xor	a, a
	ld	(_pcm_active), a
	ld	(_pcm_lock), a
	ld	a, #0x80		; 無音(中心)へ戻す
	out	(PCM_DATA), a
	ret

; 今の時刻(16bit)を HL へ。壊すのは A とフラグ。★時刻はすべてここで読む(raster.c / hot_pcm.s も)
; ★上位・下位・上位と読み、上位が揃うまで読み直す。下位→上位と 1 回ずつ読むと、その間に下位が FFh→00h へ
;   繰り上がったとき 256 カウント(1ms)大きく読める。openMSX で実際に起き、合図の時刻を待つループ
;   (raster.c の ras_tick_wait)がまだなのに抜けて、合図が 1 フレーム落ちた(2026-10-08)。
;   ★下位を読むと上位が固定される作りの機械でも、この読み方なら揃った値になる。
_pcm_now::			; ★大域: raster.c と hot_pcm.s も呼ぶ
pcm_now:
	in	a, (PCM_TIMER + 1)
	ld	h, a
	in	a, (PCM_TIMER)
	ld	l, a
	in	a, (PCM_TIMER + 1)
	cp	a, h
	jr	nz, pcm_now
	ret

; ★待ちループから 1 サンプルずつ出す送出口(pcm_service)は 2026-10-08 に外した。
;   面中は待ち時間が全体の 6〜20% しか無く、スネアが「ぶっ」と崩れた(docs/PCM調査_2026-10-07.md)。
;   いまは鳴っている間、走査線割込みが時刻どおりに出す(hot_pcm.s。raster.c の ras_next が呼ぶ)。

; ---- 次の 1 バイトを出す(時刻の判定は呼ぶ側が済ませている)。壊すのは A とフラグだけ ----
_pcm_feed::			; ★大域: hot_pcm.s(割込みで出す)も呼ぶ
pcm_feed:
	push	hl
	ld	hl, (pcm_p)
	ld	a, (hl)
	out	(PCM_DATA), a		; BUFF=1 なので次の 15.7kHz の刻みで D/A へ
	inc	hl
	ld	(pcm_p), hl
	ld	hl, (_pcm_due)		; 次の予定は「今」ではなく「前の予定 + 間隔」
	ld	a, l			; (遅れた分を次で詰めるので再生速度が伸びない)
	add	a, #PCM_PERIOD
	ld	l, a
	jr	nc, pcm_due_ok
	inc	h
pcm_due_ok:
	ld	(_pcm_due), hl
	ld	hl, (pcm_n)
	dec	hl
	ld	(pcm_n), hl
	ld	a, h
	or	a, l
	jr	z, pcm_last
	pop	hl
	ret
pcm_last:				; 鳴り終わった(全部守る。描画の途中から呼ばれる)
	push	bc
	push	de
	call	_pcm_stop
	pop	de
	pop	bc
	pop	hl
	ret
