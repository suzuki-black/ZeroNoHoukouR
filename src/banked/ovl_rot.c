/* ovl_rot.c — アフィン回転(設計メモ §2-C / ROADMAP P2 項目8-9)。
   ★まずは **自機(16x16 スプライト1枚)を実時間で回す**。宙返りを「1943 とは解釈違い」に
     するための中身であり、同時に**大型機の疑似回転・拡大縮小の前哨戦**でもある。
     使う機構(回転行列・固定小数・逆写像・増分計算)は大型機とまったく同じで、
     出力が 16x16 か 128x80 かの違いしかない。

   ★★実装の要点: **逆写像＋二重増分で、内側ループに乗算が1個も無い。**
     出力の画素 (dx,dy) から元絵の座標を引くのが逆写像:
        sx = cosθ*(dx-8) + sinθ*(dy-8) + 8
        sy = -sinθ*(dx-8) + cosθ*(dy-8) + 8
     これを差分で見ると
        dx を +1 → sx += cosθ, sy -= sinθ
        dy を +1 → sx += sinθ, sy += cosθ
     なので、行頭の値だけ持っておけば**あとは加算だけ**で走れる。
     しかも行頭の初期値は -8*cos や -8*sin ＝ **シフト(<<3)で作れる**ので、
     1フレームあたりの乗算は **0 個**。
   ★ここが今回の発見: **MULUW はアフィンの内側ループには要らない**(苦労と教訓 §13 の速度差は
     内側ループには効かない)。R800 のハード乗算が効くのは、角度や倍率から係数を作る所や、
     透視変換のような画素ごとに除算/乗算が必要な変換。**16x16 の回転は Z80 でも回る。**
     大型機でも内側ループは加算なので、支配的なコストは**画素の読み書き回数**になる。

   ★元絵は VRAM のスプライトパターン表から取り出す(そこが正本)。回した結果は
     SPR_ZERO2(プロペラのコマB)の枠へ上書きし、宙返りが終わったら元の 32B を書き戻す。
     16x16 のパターン枠に空きが1つも無いため(sprites.h 参照)、枠を奪って返す方式にした。 */
#include "types.h"
#include "vdp.h"
#include "sprites.h"

/* 16分割(22.5度刻み)の cos/sin。8.8 固定小数(256=1.0)。
   ★宙返り1回ぶんの回転コマ数がそのまま分割数になる。16 あれば滑らかに見える。 */
static const s16 rot_cos[16] = {
     256,  237,  181,   98,    0,  -98, -181, -237,
    -256, -237, -181,  -98,    0,   98,  181,  237 };
static const s16 rot_sin[16] = {
       0,   98,  181,  237,  256,  237,  181,   98,
       0,  -98, -181, -237, -256, -237, -181,  -98 };

static u8 rot_src[32];   /* 元絵(SPR_ZERO の 32B) */
static u8 rot_org[32];   /* SPR_ZERO2 の元の 32B(宙返り後に書き戻す) */
static u8 rot_dst[32];   /* 回した結果 */

/* 16x16 1bpp のビット取り出し。mode2 のパターンは
   [0..15]=左半分(x0-7)の各行 / [16..31]=右半分(x8-15)の各行。 */
static u8 src_bit(u8 x, u8 y) {
    u8 b = rot_src[(x < 8) ? y : (u8)(16 + y)];
    return (u8)(b & (0x80 >> (x & 7)));
}

/* 面開始で1回: 元絵を VRAM から取り出して覚える。 */
void ovl_rot_init(void) {
    vdp_sprite_pattern_read(SPR_ZERO,  rot_src);
    vdp_sprite_pattern_read(SPR_ZERO2, rot_org);
}

/* 角度 a(0..15)で回したコマを作り、SPR_ZERO2 の枠へ載せる。 */
void ovl_rot_frame(u8 a) {
    s16 c = rot_cos[a & 15], s = rot_sin[a & 15];
    /* 行頭(dx=0)の元座標。-8*c / -8*s はシフトで作る＝乗算ゼロ。 */
    s16 rx = (s16)(8 << 8) - (s16)(c << 3) - (s16)(s << 3);
    s16 ry = (s16)(8 << 8) + (s16)(s << 3) - (s16)(c << 3);
    u8  dy, dx, i;
    for (i = 0; i < 32; i++) rot_dst[i] = 0;
    for (dy = 0; dy < 16; dy++) {
        s16 sx = rx, sy = ry;
        for (dx = 0; dx < 16; dx++) {
            s16 ix = (s16)(sx >> 8), iy = (s16)(sy >> 8);
            /* 元絵の外は透明。★符号付きで判定すること: 負値を u8 にしてから上限だけ見ると、
               -256 のような値が 0 に化けて誤って拾う(範囲が広い変換で必ず踏む)。 */
            if (ix >= 0 && ix < 16 && iy >= 0 && iy < 16 && src_bit((u8)ix, (u8)iy))
                rot_dst[(dx < 8) ? dy : (u8)(16 + dy)] |= (u8)(0x80 >> (dx & 7));
            sx += c; sy -= s;
        }
        rx += s; ry += c;
    }
    vdp_sprite_pattern(SPR_ZERO2, rot_dst);
}

/* ============ 宙返り = 縦の圧縮(＝拡大縮小のアフィン) ============
   ★★上から見た宙返りは「面内の回転」ではない。機首を上げると**見かけの縦寸が cos(俯角) に
     縮み**、真横を向いた瞬間に一本線になり、背面に入ると上下が反転して伸び直す。
     これを素直に実装したのがこの関数で、**行を縦に再標本化するだけ**＝横方向のエイリアスが
     一切出ない。16x16 でも全コマが飛行機として読める。
   ★★★対して `ovl_rot_frame`(面内回転)は 16x16 では中間角で形が崩れる。アルゴリズムは正しく
     0/90/180/270 度は綺麗に出るが、機体の特徴(胴体2px・主翼1〜3px)が 22.5 度で
     エイリアスして潰れ、元絵を太らせても読めるようにはならなかった(Python で全16角を並べて確認)。
     **面内回転が効くのは特徴が10px以上ある大きな絵**＝大型機(表示128×80)のとき。
     そのため回転コードは残してあるが、自機の宙返りには使わない。
   ★これは**大型機の疑似拡大縮小そのもの**。倍率を cos ではなく「迫ってくる係数」に差し替えれば
     そのまま使える(ROADMAP P2 項目8 の前哨戦)。

   実装: 縦だけの拡縮なので乗算も除算も要らない。
     ・sq_h[a]    … そのコマの見かけの高さ(=|cos|×16 を丸めたもの)
     ・sq_step[a] … 出力1行あたり元絵を何行進めるか(8.8 固定小数 = 16*256/h)
     ・背面(cos<0)は元絵の行を逆から読む */
static const u8  sq_h[16]    = { 16, 15, 11,  6,  1,  6, 11, 15, 16, 15, 11,  6,  1,  6, 11, 15 };
static const u16 sq_step[16] = { 256,273,372,682,4096,682,372,273,256,273,372,682,4096,682,372,273 };

void ovl_rot_squash(u8 a) {
    u8  k = (u8)(a & 15);
    u8  h = sq_h[k], top = (u8)((16 - h) >> 1);
    u8  flip = (u8)((k >= 5) && (k <= 11));   /* cos<0 = 背面 → 上下反転 */
    /* ★標本点は各出力行の**中心**に置く(sf を半ステップから始める)。0 から始めると、
       真横のコマ(h=1)で元絵の0行目=プロペラの細い所だけを拾って**素抜けの点2つ**になる
       (実際にそうなった)。半ステップ始まりなら h=1 では主翼の行を拾う。 */
    u16 step = sq_step[k], sf = (u16)(step >> 1);
    u8  i, dy, sy;
    for (i = 0; i < 32; i++) rot_dst[i] = 0;
    for (dy = 0; dy < h; dy++) {
        sy = (u8)(sf >> 8);
        if (sy > 15) sy = 15;
        if (flip) sy = (u8)(15 - sy);
        rot_dst[(u8)(top + dy)]        = rot_src[sy];          /* 左半分 */
        rot_dst[(u8)(16 + top + dy)]   = rot_src[(u8)(16 + sy)]; /* 右半分 */
        sf += step;
    }
    vdp_sprite_pattern(SPR_ZERO2, rot_dst);
}

/* 宙返り終了: 奪っていた SPR_ZERO2 の枠を元に戻す。 */
void ovl_rot_restore(void) {
    vdp_sprite_pattern(SPR_ZERO2, rot_org);
}
