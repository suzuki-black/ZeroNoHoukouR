/* raster.h — ラスタ割り込み(R#19 / S#1 の FH)による画面分割の土台。
   ★これ自体は演出ではない。「走査線の途中で VDP の状態を変える」という 1 つの原始的な能力で、
     本企画の大型演出のうち 2 つがこの上に載る:
       ・弾のスプライト分割(32枚の総数制限を破る)  … 分割行で SAT を差し替えて同じ32枚を再利用
       ・縦方向の疑似拡大縮小/うねり(帯域ゼロ)      … 分割行ごとに R#23 を変え、表示する VRAM 行を選ぶ
       (設計メモ §2-B の衝撃波ディストーション。実装は banked/ovl_shock.c)
     どちらも VRAM 転送をほとんど増やさない＝実測で確定した「天井は VDP」(性能と高速化 §0-0)を避けられる。

   ★仕組み:
     ・R#19 に分割行を書くと、VDP は「R#19+1 行の先頭」で S#1 の FH フラグを立てる。
       R#0 の E1(bit4)を立てておくと同時に割込みも上がる。
     ・BIOS の割込みハンドラは最初に H.KEYI(0xFD9A)を CALL するので、そこへフックを刺す
       (H.TIMI(0xFD9F)は VBLANK 時しか呼ばれないので使えない。音の ISR がそちら)。
     ・ハンドラは S#1 を読んで FH を判定し(読むと FH はクリアされる)、自分の割込みなら分割処理をして
       次の分割行を R#19 へ仕込む。自分のでなければ何もせず BIOS へ戻す。

   ★守るべき作法(いずれも踏むと画面か BIOS が壊れる):
     1. S#1 を読むため R#15=1 にしたら、**必ず R#15=0 へ戻す**。BIOS は VBLANK 判定に S#0 を読む。
        既存コードは R#15 を di 区間の中でしか動かさない(vdp_cmd_wait が毎回 0 に戻す)ので、
        ハンドラ突入時の R#15 は常に 0 と仮定してよい。
     2. R#0 は BIOS の影(RG0SAV=0xF3DF)と整合させる。E1 を立てるときは影も更新する。
     3. **分割行は画面行でなく VRAM 行 0 起点で数えられる**ので、R#19 には縦スクロール量
        (g_vscroll)を足す。これを忘れるとスクロールに合わせて分割線が流れる。
     3-b. ★**分割で R#23 を書き換えたら、それ以降の分割の R#19 を新しい R#23 で計算し直す**こと。
        R#19 は VRAM 行で数えるので、表示の起点(R#23)を動かした瞬間に「画面行→VRAM行」の対応が
        変わる。ras_apply は reg==23 の書込みを見て追従用の値を更新している。
        これを忘れると、うねりを出した下側の分割行が全部ずれる。
     4. VDP の 0x99 への 2 バイト書込は割込みで壊れる。既存コードは各所で di/ei 原子化済み
        なので、このハンドラが割り込んでも安全(vdp.c 冒頭の規約)。

   ★実測が要る点: 割込みの応答遅れ(BIOS ハンドラ→H.KEYI までの分)だけ分割線は下にずれる。
     RAS_LINE_BIAS で補正する。値は openMSX/実機で実際に見て決めること。 */
#ifndef RASTER_H
#define RASTER_H

#include "types.h"

#define RAS_MAX 12   /* 1フレームに挿せる分割数の上限。
                        ★内訳の目安: スプライト表の切替 2 本(先頭=セットA / 分割行=セットB)＋
                          衝撃波ディストーション(R#23)の 8 本。
                        ★1分割=1割込み。ハンドラはレジスタ全退避＋S#1 読み＋ras_apply で
                          Z80 実測 100µs 前後。12 本で約 1.2ms/frame(R800 ならもっと軽い)。
                        ★**全行で割り込むと CPU をほぼ食い潰す**(Grauw の split guide の警告)。
                          HBLANK 中に書けるのはレジスタ4本＋パレット8エントリ程度が上限でもある。
                          増やすときは必ず実測すること。 */

#define RAS_NOREG 0xFF   /* reg にこれを入れるとレジスタ書換なし */
#define RAS_NOPAL 0xFF   /* pidx にこれを入れるとパレット書換なし */

/* 分割点 1 つ。line の直後から効く。 */
typedef struct {
    u8 line;              /* 画面行(0..211)。★0 は特別扱い＝「フレーム先頭の状態」として VBLANK 中に適用する
                             (割込み遅れで上端数ラインを取りこぼすため、分割では画面先頭を確定できない) */
    u8 reg, val;          /* 書換える VDP レジスタと値(reg=RAS_NOREG で無し) */
    u8 reg2, val2;        /* ★2本目(reg2=RAS_NOREG で無し)。フレーム先頭(line==0)で
                             「スプライト表をセットAへ戻す(R#5)」と「表示起点を戻す(R#23)」を
                             同時にやる必要があるため。分割で R#23 を動かした値は次フレームの
                             先頭まで残るので、**VBLANK で必ず基準へ戻す**こと
                             (戻さないと画面上端が前フレームのゆがみのまま出る)。 */
    u8 pidx, pr, pg, pb;  /* 書換えるパレット(pidx=RAS_NOPAL で無し)。r/b は 0-7, g は 0-7 */
} RasSplit;

/* ★分割表は**高位フリー帯へ固定配置**する。常駐_DATA は 0xE000 が天井(それを越えるとバンクシーンの
   static に踏み潰される=設定値が化ける。Makefile が機械検証している)で、RAS_MAX を増やすと
   すぐ溢れた。既存の固定帯: g_card_ram 0xE100 / ship_ram 0xE700 / fb_ram 0xE900 /
   prof 0xEB00 / g_cbul 0xEC00-0xEDFF / オーバレイの static 0xEE00-。その次の空きを使う。
   ★オーバレイ(ovl_shock.c)からも書くので、固定番地であること自体が都合がよい。 */
#define RAS_ADDR 0xEF00
extern RasSplit __at(RAS_ADDR) g_ras[RAS_MAX];   /* 分割表。line の昇順に詰めること */
extern u8 g_ras_n;                /* 今フレームの有効分割数(0=分割なし) */
extern u8 g_ras_i;                /* 次に処理する分割の添字(ISR が進める) */

void raster_init(void);   /* 起動時1回: H.KEYI へフックを設置(sound_init の後に呼ぶ) */
void raster_arm(u8 n);    /* 今フレームの分割数を確定(表の更新だけ。R#19 の仕込みは VBLANK 割込みが行う) */
void raster_off(void);    /* E1 を落として分割を止める(シーン遷移/バンキング前) */

#endif /* RASTER_H */
