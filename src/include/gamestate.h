/* gamestate.h — ゲーム全体で共有する状態(常駐)。config(バンク)が設定し、gameplay が読む。 */
#ifndef GAMESTATE_H
#define GAMESTATE_H

#include "types.h"

extern u8  g_difficulty;   /* 0=EASY / 1=NORMAL / 2=HARD */
extern u8  g_lives_idx;    /* 残機テーブル添字(0=2 / 1=3 / 2=5) */
extern u8  g_durability;   /* 1機あたりの耐久HP(1..9, 既定3)。設定メニュー(耐久) */
extern u8  g_stage_sel;    /* 開始ステージ(0基点。現状0のみ)。設定メニュー(ステージ選択) */
extern u8  g_continue;     /* 1=ゲームオーバーでコンティニュー可(既定1)。設定メニュー(継続) */
extern u8  g_invinc;       /* 1=無敵(被弾しても残機/耐久を減らさない)。設定メニュー(無敵) */
extern u16 g_score;        /* スコア(撃破で加算) */
extern u16 g_hiscore;      /* ハイスコア(セッション内。将来SRAM保存) */
extern u8  g_lives;        /* 現在の残機(面開始で g_lives_idx から設定) */
extern u8  g_php;          /* 現在の耐久HP(面開始/ミスで g_durability から補充) */

extern u8  g_rage;         /* 1=レイジ(ボス最後の砲台=速射の最終抵抗)。diff_interval が更に短縮 */

/* ★メガクラッシュ(設計メモ §4-1「安い出力で最大の爽快」)。Bボタンで発動。
   画面全体を雷光が覆い(スクロールもBGMも止める)、数瞬のちに画面上の敵弾だけが消える。
   出力はパレット16色の書換だけ＝VDP帯域ほぼゼロ(性能と高速化 §0-0 の「重い計算・軽い出力」)。 */
#define CRUSH_MAX    3    /* 1回の挑戦で使える回数(画面下に表示)。3までは棒の本数、4以上は棒＋数字 */
/* ★演出の台本。g_crush_t は CRUSH_FRAMES から 0 へ1フレームずつ減る(=残りフレーム数)。
     t=88/80/72 … 稲妻を描く(その直後のフレームで閃光。ovl_palette の crush_lv[] 参照)
     t=66       … 描いた稲妻を世界の正本から消す(津波が始まる前に片付ける)
     t=64..1    … 津波が画面下(自機側)から斜めに駆け上がる。step = CRUSH_WAVE_T0 - t
     t=32       … 波が画面中央を越えた瞬間に敵弾を消す(波が攫っていった、という見え方)
     t=0        … 波スプライトを片付けて BGM を**続きから**再開
   ★クラッシュ中は scene.c が 60fps で回す(ゲームは全部止まっているので速度定数に影響しない)。
   ★フレーム数だけでなく **1フレームの実時間** を測って決めること。稲妻を描くフレームは
     LINE を数百本発行するので 1枚で 0.3〜0.45秒かかる。最初 74 フレーム/30fps で組んだら
     発動から再開まで 4.5秒もかかっていた(実測)。ボムとしては長すぎる。 */
#define CRUSH_FRAMES  96
#define CRUSH_WIPE    32  /* 残りフレームがこの値になった瞬間に敵弾を消す */
#define CRUSH_ERASE   66  /* 稲妻を消す(世界の正本から引き直す)タイミング */

/* ★津波は「斜め一列のスプライト」で表現する。
   ・BG へ焼く方式(疑似スプライト)はパターン/VRAM を大きく食う上に、毎フレーム下地を戻す必要が
     あって1フレームが重くなり、結局カクカク大きく飛ばすしかなくなる。
   ・スプライトなら1フレームの仕事は属性16枚の書換だけ＝ほぼ無料。**1px単位で動かせる**ので
     ドット単位に滑らかに上がる。
   ・**斜めに並べる**のが肝。V9938 は1走査線8枚までしか出せないが、16px幅のコマを
     CRUSH_WAVE_SLOPE px ずつ下げて並べれば、1本の走査線に載るのは高々 16/SLOPE+1 枚
     (SLOPE=6 なら3枚)で、8枚制限に当たらない。
   ・絵はパターン4種を i+step で巡回させ、泡が横へ流れて見えるようにする。色は行別カラーテーブル
     (白い波頭→泡→明るい水→背面の影)＝1枚のビットマップで立体的な波になる。 */
#define CRUSH_WAVE_T0    64  /* 津波の開始 t */
#define CRUSH_WAVE_T1    1   /* 津波の終了 t(64ステップ×DY=320px で画面を抜け切る) */
#define CRUSH_WAVE_N     16  /* コマ数(16px×16=画面幅256) */
#define CRUSH_WAVE_SLOT  16  /* 使うスプライト slot(16..31)。HUD(0..8)と凍結中の敵(9..15)より後ろ
                                ＝自機や敵機は波の手前に出る(飛行機は水面より上に居るのだから正しい) */
#define CRUSH_WAVE_SLOPE 6   /* 1コマごとに下げる px(斜めの角度)。大きいほど急な斜め */
#define CRUSH_WAVE_Y0    212 /* 波頭の開始 画面Y(画面下端=見えない位置から上がってくる) */
#define CRUSH_WAVE_DY    5   /* 1フレームの上昇量 px(60fps で 300px/秒。細かく動くほど滑らかに見える) */
extern u8  g_crush;        /* 残り使用回数(画面下に表示) */
extern u8  g_crush_t;      /* >0=発動中の残りフレーム。パレットエンジンが雷光の強さに使う */

/* ★画面ビューア(デバッグ/確認用): config が設定し stage_init が分岐。各画面を個別に表示できる。
   0=通常ゲーム / 1=ステージ説明カードのみ / 2=撃破結果(SUNK)画面のみ。エンディングは config が SC_ENDING を直接返す。 */
extern u8  g_view;

/* 難易度で発火/出現間隔をスケール(EASY=遅い/HARD=速い)。base×{5,4,3}/4、下限1。全系統の発砲・出現に適用。
   レイジ中は更に×2/3。 */
u8 diff_interval(u8 base);

#endif /* GAMESTATE_H */
