/* ★メガクラッシュ(設計メモ §4-1「安い出力で最大の爽快」)。Bボタンで発動。
   画面全体を雷光が覆い(スクロールもBGMも止める)、数瞬のちに画面上の敵弾だけが消える。
   出力はパレット16色の書換だけ＝VDP帯域ほぼゼロ(性能と高速化 §0-0 の「重い計算・軽い出力」)。 */
#define CRUSH_MAX    3    /* 1回の挑戦で使える回数(画面下に表示)。3までは棒の本数、4以上は棒＋数字 */
/* ★演出の台本。g_crush_t は CRUSH_FRAMES から 0 へ1フレームずつ減る(=残りフレーム数)。
   クラッシュ中は scene.c が 60fps で回す(ゲームは全部止まっているので速度定数に影響しない)。
     t=78..73 … 地鳴り(画面揺れ＋低いノイズ)。「ゴゴゴゴ」
     t=72/66/60 … 稲妻を描く(その直後のフレームで閃光。ovl_palette の crush_lv[] 参照)
     t=54     … 描いた稲妻を世界の正本から消す(津波が始まる前に片付ける)
     t=46..1  … 画面幅の水の壁が**加速しながら**駆け上がる。step = CRUSH_WAVE_T0 - t
     t=24     … 波が画面中央を越えた瞬間に敵弾を消す(波が攫っていった、という見え方)
     t=0      … 波を片付け、HUDの色/パターンを戻し、BGM を**続きから**再開
   ★フレーム数だけでなく **1フレームの実時間** を測って決めること。稲妻を描くフレームは
     LINE を数百本発行するので 1枚で 0.3〜0.45秒かかる。 */
#define CRUSH_FRAMES  78
#define CRUSH_RUMBLE  73  /* この t までは地鳴りだけ(揺れ＋ノイズ) */
#define CRUSH_WIPE    24  /* 残りフレームがこの値になった瞬間に敵弾を消す */
#define CRUSH_ERASE   54  /* 稲妻を消す(世界の正本から引き直す)タイミング */

/* ★津波は **スプライト拡大(R#1 bit0=MAG)** を使った「画面幅の水の壁」。詳細は ovl_crush.c。
   ・8列×4段=32枚(全スプライト)で 256×128px。1走査線はちょうど8枚のまま。
   ・MAG は全スプライトに効くので、津波の間は HUD も敵も出さない。
   ・**等加速度**で上がる(dist = step*step / CRUSH_WAVE_ACC)。一定速度だと板が平行移動する
     ようにしか見えない。出だしはほぼ止まって地鳴り、後半で一気に駆け上がる。 */
#define CRUSH_WAVE_T0    46  /* 津波の開始 t(step=0) */
#define CRUSH_WAVE_T1    1   /* 津波の終了 t(step=45)。移動量は CRUSH_WAVE_ACC を参照 */
#define CRUSH_WAVE_Y0    212 /* 波頭の開始 画面Y(画面下端=見えない位置から上がってくる) */
#define CRUSH_WAVE_ACC   5   /* 加速度の逆数。小さいほど速く加速する。
                                ★必要な移動量 = 画面212px ＋ 壁の縦の広がり(4段128px＋傾き28px) = 368px。
                                  step は 0..45 なので 45*45/5 = 405px で抜け切る。
                                  大きすぎると画面の途中で止まり、小さすぎると早く抜けて残りが空振り */
#define CRUSH_WAVE_SHEAR 4   /* 斜めの傾き(列ごとに下げる画面px)。★32/列数(8)=4 が上限(ovl_crush.c) */
extern u8  g_crush;        /* 残り使用回数(画面下に表示) */
/* ★自機弾のパワーアップ(ROADMAP P2-B / A1)。0=通常 / 1〜3=太い弾を縦・左上・右上へ3発。
   威力は「半分単位」で数える(耐久もすべて2倍にしてある): 通常2 / 1段目4(2倍) / 2段目5(2.5倍) / 3段目6(3倍)＋貫通。
   海モードに1機だけ出る銀の敵機を落とすと増槽が出て、取ると+1。ミス・新規ゲーム・最終面の開始で0に戻る。 */
extern u8  g_pwr;
extern u8  g_pdmg;         /* 今の段階の威力(半分単位)。発砲時に g_pwr から決める(対空砲の当たり判定はこれを見る) */
#define PWR_MAX 3
extern u8  g_jam_t;                 /* >0: 電探妨害の合図(5面の中ボス戦でボムを押した) */
extern u8  g_pwr_icon;              /* 1=段階のアイコンを出す(ent_draw_all が最低優先で描く) */
extern u8 pwr_col[PWR_MAX + 1][16];   /* 段階ごとの山形の行別色(0=その行は出さない)。通常弾=1本〜最終=4本 */
#define PWR_ICON_X 120              /* 画面下の中央(16x16)。ボムの棒と同じ行に置いて、HUD が占める走査線を増やさない */
#define PWR_ICON_Y 190
extern u8  g_drop;         /* 1=銀の敵機が落ちた(g_drop_x/y にその位置)。増槽はオーバレイが出す */
extern u8  g_fade;         /* 0 以外: 敵をフェードアウト中(残りフレーム。FADE_T から数える)。0 になった瞬間に消す */
extern u8  g_alert;        /* 1=警報の表示中。縦スクロールと海の塗り直しを止める(最終面は面の頭から立てておく) */
#define FADE_T  32         /* フェードアウトの長さ(8フレームずつ 4 段) */
#define ALERT_TICKS 150    /* 警報の長さ(60Hz の割込みで数える=2.5秒。文字を描く時間も含む。ゲームの重さに左右されない) */
extern s16 g_drop_x, g_drop_y;
extern u8  g_crush_t;      /* >0=発動中の残りフレーム。パレットエンジンが雷光の強さに使う */

/* ★衝撃波ディストーション(設計メモ §2-B)。砲台撃破/被弾の瞬間に、震源から上下へ広がる
   「縦のうねり」を走らせる。
   ★出力は **R#23 を走査線の途中で書き換えるだけ**＝VRAM 転送ゼロ。R#23 は「画面のどの VRAM 行を
     先頭に表示するか」なので、帯ごとに値を変えると表示が縦にずれる＝ゆがみになる。
     ROADMAP §2-B ② の調査で見つけた手。分割の土台は raster.c。
   ★リングは震源の上下に1本ずつ、1リング=2分割(帯の入口でずらし・出口で戻す)＝計4分割。
     ★分割は間隔が狭いと発火しない(割込み応答の遅れ)。帯幅は ovl_shock.c の SHOCK_MIN_GAP を参照。 */
#define SHOCK_FRAMES  14  /* 発生から収まるまで(30fps で約0.47秒) */
#define SHOCK_SPEED    7  /* リングが1フレームに広がる px */
#define SHOCK_AMP     10  /* 変位の最大 px(発生直後。以後 0 まで減衰) */
extern u8  g_shock_t;      /* >0=衝撃波の残りフレーム */
extern u8  g_shock_y;      /* 震源の画面Y(0..211) */
void shock_at(s16 sy);     /* 衝撃波を起こす(震源の画面Y。画面外なら無視) */

/* ★宙返り(設計メモ §2-C の前哨戦 / ROADMAP P2 項目9)。**1943 とは「解釈違い」にする**:
     ・1942 系列は固定の数コマ＋残機ごとの回数制(パニックボタン)。
     ・こちらは **★C のアフィン回転で機体が本当に回り**(banked/ovl_rot.c)、
       **回数制ではなくクールダウン制**、**無敵ではなく「面から外れる」**(回っている間は撃てず、
       弾は下を抜ける)。抜けに ★B の衝撃波リングを小さく出して自分の演出資産へ繋げる。
   ★宙返りは実装として大型機の疑似回転・拡大縮小の前哨戦でもある(機構が同じ)。 */
#define LOOP_FRAMES 16   /* 宙返りの長さ(=回転コマ数。ovl_rot.c の分割数と一致させる) */
#define LOOP_CD     45   /* クールダウン(30fps で1.5秒)。回数制にしない代わりの制約 */
extern u8  g_loop_t;       /* >0=宙返り中の残りフレーム(=回転角の逆順) */
extern u8  g_loop_cd;      /* >0=クールダウン中(宙返りできない) */
extern u8  g_loop_alt;     /* 宙返り中の高度(0..16)。自機の影をこれだけ離す＝高く上がって見える */

/* ★画面ビューア(デバッグ/確認用): config が設定し stage_init が分岐。各画面を個別に表示できる。
   0=通常ゲーム / 1=ステージ説明カードのみ / 2=撃破結果(SUNK)画面のみ。エンディングは config が SC_ENDING を直接返す。 */
extern u8  g_view;

/* 難易度で発火/出現間隔をスケール(EASY=遅い/HARD=速い)。base×{5,4,3}/4、下限1。全系統の発砲・出現に適用。
   レイジ中は更に×2/3。 */
u8 diff_interval(u8 base);

#endif /* GAMESTATE_H */
